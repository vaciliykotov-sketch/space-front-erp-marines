using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

// Stories-start: дополнительные using
using Robust.Client.Graphics;
using System.Collections.Generic;
using System.Numerics;
// Stories-end

namespace Content.Client.Info;

[GenerateTypedNameReferences]
public sealed partial class RulesPopup : Control
{
    private float _timer;

    public float Timer
    {
        get => _timer;
        set
        {
            WaitLabel.Text = Loc.GetString("ui-rules-wait", ("time", MathF.Floor(value)));
            _timer = value;
        }
    }

    public event Action? OnQuitPressed;
    public event Action? OnAcceptPressed;

    // Stories-start: изменённый член (наша версия, см. PATCHES.md)
    public RulesPopup()
    {
        RobustXamlLoader.Load(this);

        for (var idx = 0; idx < ChecklistItems.Length; idx++)
        {
            var item = ChecklistItems[idx];
            var row = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                HorizontalExpand = true,
                VerticalExpand = true,
            };

            var checkButton = new Button
            {
                MinSize = new Vector2(22, 22),
                MaxSize = new Vector2(22, 22),
                Text = "☐",
            };
            checkButton.StyleClasses.Clear();
            checkButton.Label.FontColorOverride = Color.White;
            checkButton.Label.HorizontalAlignment = HAlignment.Center;
            checkButton.Label.VerticalAlignment = VAlignment.Center;

            var textLabel = new RichTextLabel
            {
                HorizontalExpand = true,
                MouseFilter = MouseFilterMode.Ignore,
            };
            textLabel.SetMessage(" —  " + item);

            row.AddChild(checkButton);
            row.AddChild(textLabel);

            var entry = (checkButton, false);
            _checkboxes.Add(entry);
            checkButton.OnPressed += _ =>
            {
                var i = _checkboxes.IndexOf(entry);
                if (i < 0)
                    return;
                var cur = _checkboxes[i];
                var next = !cur.Checked;
                cur.CheckButton.Text = next ? "🗹" : "☐";
                _checkboxes[i] = (cur.CheckButton, next);
                RefreshAccept();
            };

            CheckboxContainer.AddChild(row);

            if (idx < ChecklistItems.Length - 1)
            {
                var divider = new PanelContainer
                {
                    HorizontalExpand = true,
                    MinHeight = 1,
                    PanelOverride = new StyleBoxFlat
                    {
                        BackgroundColor = Color.White,
                    },
                    MouseFilter = MouseFilterMode.Ignore,
                };
                CheckboxContainer.AddChild(divider);
            }
        }

        DisclaimerText1.SetMessage("Этот сервер содержит ОТКРОВЕННЫЙ КОНТЕНТ ДЛЯ ВЗРОСЛЫХ: полное ERP без ограничений, сексуальное рабство, изнасилование, некрофилию и иные сексуальные фетиши, а также шокирующий контент. Заходя на сервер, вы подтверждаете, что полностью ознакомлены с этим и добровольно принимаете всё вышеперечисленное.");
        DisclaimerText2.SetMessage("Если вы НЕ согласны с условиями игры, вам ЗАПРЕЩЕНО здесь играть, и вы можете покинуть сервер в любой момент. Администрация сервера НЕ несёт ответственности за ваше ментальное состояние, психологические травмы и любые последствия, связанные с увиденным или произошедшим на сервере. Мы вас предупредили.");
        DisclaimerText3.SetMessage("Любые претензии к серверу, администрации и игрокам, связанные с содержанием игры, отыгрышем или действиями других игроков, вы ОТКЛОНЯЕТЕ добровольно и безоговорочно.");

        RulesText1.SetMessage("Этот сервер — открытый бета-тест нашего кастомного режима «Альфа-Браво против Дельта-Чарли».");
        RulesText2.SetMessage("На сигнал бедствия прилетели два корабля класса «Алмаер». Сначала бой идёт на планете, затем — штурм вражеского Алмаера.");
        RulesText3.SetMessage("ERP разрешено, уровень отыгрыша — средний (MRP). Сообщайте о любых багах в наш Discord: https://discord.gg/PhHV3EeZqs");
        RulesText4.SetMessage("Я мог бы ещё расписать кучу правил - как это обычно делают на других серверах, но все они сводятся к одному и быстрее сказать так — просто не будьте мудаком, не портите игру другим людям, общайтесь культурно и вежливо, приятной игры!");

        DisclaimerContinueButton.OnPressed += _ =>
        {
            PageDisclaimer.Visible = false;
            PageRules.Visible = true;
        };

        AcceptButton.OnPressed += OnAcceptButtonPressed;
        QuitButton.OnPressed += OnQuitButtonPressed;
        QuitButton2.OnPressed += OnQuitButtonPressed;

        RefreshAccept();
    }
    // Stories-end

    private void OnQuitButtonPressed(BaseButton.ButtonEventArgs obj)
    {
        OnQuitPressed?.Invoke();
    }

    private void OnAcceptButtonPressed(BaseButton.ButtonEventArgs obj)
    {
        OnAcceptPressed?.Invoke();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (!AcceptButton.Disabled)
            return;

        if (Timer > 0.0)
        {
            if (Timer - args.DeltaSeconds < 0)
                Timer = 0;
            else
                Timer -= args.DeltaSeconds;
        }
        else
        {
            AcceptButton.Disabled = false;
        }
    }
}
