using Content.Shared.Ghost;
using Content.Shared._SpaceFront.Respawn;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Network;
using Robust.Shared.Timing;
using Robust.Shared.IoC;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.CustomControls;

namespace Content.Client._SpaceFront.Respawn;

[GenerateTypedNameReferences]
public sealed partial class SquadWarDeathWindow : Control
{
    public float SecondsLeft;

    public SquadWarDeathWindow()
    {
        RobustXamlLoader.Load(this);

        // Чёрная обводка по периметру окна.
        Panel.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = Color.FromHex("#1b1b1f"),
            BorderColor = Color.Black,
            BorderThickness = new Thickness(4),
        };

        LeaveNowButton.OnPressed += _ =>
        {
            IoCManager.Resolve<IEntityManager>().RaisePredictiveEvent(new SquadWarLeaveNowEvent());
        };

        ReturnButton.OnPressed += _ =>
        {
            // Ванильный запрос РМС: попытка вернуться в тело.
            IoCManager.Resolve<IEntityManager>().RaisePredictiveEvent(new GhostReturnToBodyRequest());
        };
    }

    public void UpdateTimer()
    {
        TextLabel.Text = $"Будучи призраком, нельзя подсматривать за другими игроками.\nВы будете принудительно выкинуты в лобби через {Math.Max(0, (int)Math.Ceiling(SecondsLeft))} секунд.";
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (SecondsLeft <= 0)
            return;

        SecondsLeft -= args.DeltaSeconds;
        if (SecondsLeft < 0)
            SecondsLeft = 0;
        UpdateTimer();
    }
}
